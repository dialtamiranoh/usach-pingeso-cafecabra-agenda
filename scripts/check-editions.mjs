import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { Miniflare, convertV4MiniflareOptions } from 'miniflare';
import { createServer } from 'vite';

const mf = new Miniflare(convertV4MiniflareOptions({ modules: true, script: 'export default { fetch() { return new Response("ok") } }', d1Databases: { DB: 'editions-test' } }));
const server = await createServer({ configFile: 'frontend/vite.config.ts', server: { middlewareMode: true }, appType: 'custom' });
try {
  const db = await mf.getD1Database('DB');
  async function executeFile(file) {
    const sql = await readFile(file, 'utf8');
    await db.batch(sql.split('--> statement-breakpoint').filter(part => part.trim()).map(part => db.prepare(part)));
  }
  for (const file of (await readdir('backend/migrations')).filter(file => file.endsWith('.sql') && !file.startsWith('0004')).sort()) await executeFile(`backend/migrations/${file}`);
  await db.prepare("INSERT INTO user(id,name,email,email_verified,created_at,updated_at) VALUES('owner','Dueño de prueba','owner@example.com',0,unixepoch(),unixepoch())").run();
  await db.prepare("INSERT INTO tipo_evento(id,nombre,requiere_pago) VALUES(1,'Curso',1),(2,'Evento',0)").run();
  await db.prepare("INSERT INTO ubicaciones(id,nombre) VALUES(1,'Café de prueba')").run();
  await db.prepare("INSERT INTO eventos(id,tipo_evento_id,ubicacion_id,nombre,precio,cupo_maximo,estado) VALUES(1,1,1,'Master Class',65000,1,'ABIERTO'),(2,1,1,'Intensivo',220000,2,'ABIERTO'),(3,2,1,'Cata',0,1,'ABIERTO'),(4,1,1,'Antigua con fechas alternativas',65000,3,'ABIERTO'),(5,1,1,'Antigua de una fecha',65000,3,'ABIERTO')").run();
  await db.prepare("INSERT INTO fechas(id,evento_id,fecha,horario) VALUES(1,1,'2026-12-14','10:00-12:00'),(2,1,'2026-12-21','09:00-11:00'),(3,2,'2026-12-07','09:00-15:30'),(4,2,'2026-12-08','09:00-15:30'),(5,3,'2026-12-28','16:00-18:00'),(6,4,'2026-12-14','10:00-12:00'),(7,4,'2026-12-21','10:00-12:00'),(8,5,'2026-12-14','10:00-12:00')").run();
  await db.prepare("INSERT INTO configuracion(clave,valor) VALUES('evento:2:modalidad_fechas','CONJUNTAS')").run();
  await db.prepare("INSERT INTO reservas(id,evento_id,codigo,reservado_por_nombre,reservado_por_correo,reservado_para_nombre,estado,expira_en,monto_esperado) VALUES(100,4,'OLD-AMBIGUOUS','Antigua','old@example.com','Antigua','RESERVADO',unixepoch()+3600,65000),(101,5,'OLD-SINGLE','Antigua única','single@example.com','Antigua única','CONFIRMADO',NULL,65000)").run();
  await executeFile('backend/migrations/0004_far_ogun.sql');
  assert.equal((await db.prepare('SELECT COUNT(*) AS n FROM ediciones').first()).n, 7);
  assert.equal((await db.prepare('SELECT edicion_id FROM reservas WHERE id=100').first()).edicion_id, null);
  assert.equal((await db.prepare('SELECT edicion_id FROM reservas WHERE id=101').first()).edicion_id, 'fecha-8');
  assert.equal((await db.prepare("SELECT COUNT(*) AS n FROM fechas WHERE edicion_id='evento-2'").first()).n, 2);
  await executeFile('backend/seeds/ediciones.sql');
  assert.equal((await db.prepare('SELECT COUNT(*) AS n FROM ediciones').first()).n, 7);
  assert.equal((await db.prepare('PRAGMA foreign_key_check').all()).results.length, 0);

  const { enrollmentRoutes } = await server.ssrLoadModule('/backend/src/routes/enrollments.ts');
  const { listEvents } = await server.ssrLoadModule('/backend/src/routes/catalog.ts');
  const { enrollmentDetail, assignReservationEdition, decideReservation } = await server.ssrLoadModule('/backend/src/services/reservation-decisions.ts');
  const { toCatalogItem } = await server.ssrLoadModule('/frontend/src/features/catalog/catalog-data.ts');
  const env = { APP_ENV: 'local', cafe_cabra_agenda_db: db, ADMIN_EMAIL: 'owner@example.com', AGENDA_HUB: { idFromName: () => 'test', get: () => ({ fetch: async () => new Response('ok') }) } };
  const payload = (eventId, editionId, email = 'same@example.com') => ({ eventId: String(eventId), editionId, requestId: crypto.randomUUID(), name: 'Persona de prueba', email, phone: '+56 9 0000 0000', instagram: '', dietaryPreference: '', dietaryOther: '', allergyStatus: '', allergyDetails: '', notes: 'Prueba aislada', confirmed: true, payerSameAsAttendee: true, payerName: '', payerRut: '12.345.678-5', originBank: 'BancoEstado', accountType: 'Cuenta Corriente', accountLastFour: '1234' });
  const send = body => enrollmentRoutes.request('/inscripciones', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) }, env);
  const book = async body => { const response = await send(body); const result = await response.json(); assert.equal(response.status, 201, JSON.stringify(result)); return result; };
  const state = async eventId => (await listEvents(db, true)).find(event => event.id === String(eventId));
  let master = await state(1);
  assert.deepEqual(master.editions.map(edition => edition.remainingSeats), [1, 1]);
  assert.equal(toCatalogItem(master).sessions.length, 2);
  const day14 = payload(1, 'fecha-1');
  const first = await book(day14);
  assert.equal(first.editionId, 'fecha-1');
  master = await state(1);
  assert.deepEqual(master.editions.map(edition => edition.remainingSeats), [0, 1], 'El día 14 no descuenta cupos del 21');
  const day21 = payload(1, 'fecha-2');
  await book(day21); // Mismo correo y RUT, diferente edición: permitido.
  assert.equal((await send(payload(1, 'fecha-1', 'otro@example.com'))).status, 409);
  assert.equal((await send({ ...day14, editionId: 'fecha-2' })).status, 409, 'No reutiliza una solicitud para otra edición');
  const missing = payload(1, 'fecha-1'); delete missing.editionId;
  assert.equal((await send(missing)).status, 400);
  assert.equal((await send(payload(1, 'fecha-5'))).status, 400, 'No acepta una edición de otra actividad');
  assert.equal((await send(payload(1, "' OR 1=1"))).status, 400);
  await db.prepare('UPDATE eventos SET precio=99000 WHERE id=1').run();
  const replay = await send(day21);
  assert.equal(replay.status, 200);
  assert.equal((await replay.json()).transfer.monto, 65000);
  const firstId = (await db.prepare('SELECT id FROM reservas WHERE codigo=?').bind(first.code).first()).id;
  await decideReservation(db, firstId, 'owner', { requestId: crypto.randomUUID(), action: 'CANCELAR', reason: 'Prueba de liberación de cupos.', paymentVerified: false });
  assert.deepEqual((await state(1)).editions.map(edition => edition.remainingSeats), [1, 0]);
  await book(payload(1, 'fecha-1'));
  const day21Id = (await db.prepare('SELECT id FROM reservas WHERE codigo=?').bind(`CC-${day21.requestId.toUpperCase()}`).first()).id;
  const confirmed = await decideReservation(db, day21Id, 'owner', { requestId: crypto.randomUUID(), action: 'CONFIRMAR', reason: '', paymentVerified: true });
  assert.equal(confirmed.detail.dates.length, 1);
  assert.equal(confirmed.detail.dates[0].date, '2026-12-21');
  assert.ok(confirmed.detail.notification.message.includes('21 de diciembre'));
  assert.ok(!confirmed.detail.notification.message.includes('14 de diciembre'));
  await book(payload(2, 'evento-2', 'intensivo@example.com'));
  const intensive = await state(2);
  assert.equal(intensive.editions.length, 1);
  assert.equal(intensive.editions[0].dates.length, 2);
  assert.equal(intensive.editions[0].remainingSeats, 1, 'Dos jornadas consumen un solo cupo');
  assert.equal(toCatalogItem(intensive).sessions[0].days.length, 2);
  const concurrent = await Promise.all([send(payload(3, 'fecha-5', 'a@example.com')), send(payload(3, 'fecha-5', 'b@example.com'))]);
  assert.deepEqual(concurrent.map(response => response.status).sort(), [201, 409]);
  const old = await enrollmentDetail(db, 100);
  assert.equal(old.needsEdition, true);
  assert.equal(old.canConfirm, false);
  assert.equal(old.dates.length, 0);
  await assert.rejects(decideReservation(db, 100, 'owner', { requestId: crypto.randomUUID(), action: 'CONFIRMAR', reason: '', paymentVerified: true }));
  await assert.rejects(assignReservationEdition(db, 100, 'fecha-1', 'owner'));
  assert.deepEqual((await state(4)).editions.map(edition => edition.remainingSeats), [2, 2], 'La reserva antigua retiene cupo conservadoramente');
  const assigned = await assignReservationEdition(db, 100, 'fecha-6', 'owner');
  assert.equal(assigned.canConfirm, true);
  assert.equal(assigned.dates[0].date, '2026-12-14');
  assert.deepEqual((await state(4)).editions.map(edition => edition.remainingSeats), [2, 3]);
  await assert.rejects(assignReservationEdition(db, 100, 'fecha-7', 'owner'), 'No mueve reservas ya asignadas');
  assert.equal((await db.prepare('PRAGMA foreign_key_check').all()).results.length, 0);
  console.log('OK: migración sin inventar fechas; edición persistida; cupos independientes; dos jornadas/un cupo; duplicados por edición; concurrencia; correo con fecha exacta y asignación controlada de reservas antiguas.');
} finally { await server.close(); await mf.dispose(); }
